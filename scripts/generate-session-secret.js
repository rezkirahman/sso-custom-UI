const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

console.log("Generating 32-character SESSION_SECRET...");

const secret = crypto.randomBytes(32).toString('hex').substring(0, 32);

const envLocalPath = path.join(process.cwd(), '.env.local');

let envContent = '';
if (fs.existsSync(envLocalPath)) {
  envContent = fs.readFileSync(envLocalPath, 'utf8');
}

if (envContent.includes('SESSION_SECRET=')) {
  console.log("SESSION_SECRET already exists in .env.local. Replacing it...");
  envContent = envContent.replace(/SESSION_SECRET=.*/g, `SESSION_SECRET="${secret}"`);
} else {
  envContent += `\n# Generated by generate-session-secret.js\nSESSION_SECRET="${secret}"\n`;
}

fs.writeFileSync(envLocalPath, envContent.trim() + '\n');
console.log("✅ Successfully injected SESSION_SECRET into .env.local!");
